"""Create Vercel's generated public/ directory from a public-file allowlist."""
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
ASSET_TYPES = {'.css', '.js', '.svg', '.png', '.webp', '.jpg', '.jpeg',
               '.gif', '.ico', '.json', '.woff', '.woff2'}
MARKER = '.cocegn-public-bundle'


def prepare(source: Path, destination: Path):
    source, destination = source.resolve(), destination.absolute()
    if destination.is_symlink() or destination == source or destination in source.parents:
        raise ValueError('Unsafe public output directory')
    files = [source / name for name in ('index.html', '404.html', 'robots.txt')]
    if (source / 'sitemap.xml').exists():
        files.append(source / 'sitemap.xml')
    for folder in ('pages', 'assets'):
        for path in (source / folder).rglob('*'):
            if path.is_symlink():
                raise ValueError(f'Symlink cannot be published: {path.relative_to(source)}')
            relative = path.relative_to(source)
            if any(part.startswith('.') for part in relative.parts):
                continue
            if path.is_file() and (path.suffix == '.html' if folder == 'pages' else path.suffix in ASSET_TYPES):
                files.append(path)
    for path in files:
        if path.is_symlink():
            raise ValueError('Symlink cannot be published')
        if not path.is_file():
            raise ValueError(f'Required public file is missing: {path.name}')
    if destination.exists():
        if not (destination / MARKER).is_file():
            raise ValueError('Refusing to replace an unrecognised output directory')
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    (destination / MARKER).write_text('Generated by scripts/prepare_public.py\n')
    for path in files:
        target = destination / path.relative_to(source)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
    print(f'Prepared {len(files)} public files; backend, configuration and documents excluded.')


if __name__ == '__main__':
    prepare(ROOT, ROOT / 'public')
